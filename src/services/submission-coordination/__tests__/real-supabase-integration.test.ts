const LOCAL_SERVICE_KEY = process.env.LOCAL_SUPABASE_SERVICE_ROLE_KEY || 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6InNlcnZpY2Vfcm9sZSIsImV4cCI6MTk4MzQxMjgwMH0.CRXP_placeholder_local_service_key';

export async function checkLocalSupabaseAvailable(): Promise<boolean> {
  try {
    const res = await fetch(`${LOCAL_SUPABASE_URL}/rest/v1/`, {
      method: 'GET',
      headers: { apikey: LOCAL_ANON_KEY },
      signal: AbortSignal.timeout(2000),
    });
    return res.status < 500;
  } catch {
    return false;
  }
}

export async function runRealSupabaseIntegrationTests(): Promise<{
  executed: boolean;
  passed: number;
  failed: number;
  message?: string;
}> {
  console.log('\n=============================================================');
  console.log('--- PPEye Phase 4.5: Real Local Supabase Integration Suite ---');
  console.log('=============================================================');

  const isAvailable = await checkLocalSupabaseAvailable();
  if (!isAvailable) {
    const reason =
      `Local Supabase instance is NOT reachable at ${LOCAL_SUPABASE_URL}.\n` +
      `Docker or local Supabase CLI is not active on this environment.\n` +
      `Per Phase 4.5 safety constraints, tests against remote Supabase are STRICTLY FORBIDDEN.`;
    console.warn(`\n[LOCAL INTEGRATION NOTICE] ${reason}\n`);
    return {
      executed: false,
      passed: 0,
      failed: 0,
      message: reason,
    };
  }

  console.log(`Connected to local Supabase at: ${LOCAL_SUPABASE_URL}`);
  let passed = 0;
  let failed = 0;

  async function test(name: string, fn: () => Promise<void>): Promise<void> {
    try {
      await fn();
      console.log(`  ✔ [PASS] ${name}`);
      passed++;
    } catch (err: any) {
      console.error(`  ✘ [FAIL] ${name}`);
      console.error(`    ${err?.message ?? err}`);
      failed++;
    }
  }

  // Admin client for test fixture provisioning
  const adminClient = createClient(LOCAL_SUPABASE_URL, LOCAL_SERVICE_KEY, {
    auth: { persistSession: false },
  });

  // Client overrides for service testing
  setDbClientOverride(adminClient as any);
  setSupabaseStorageClientOverride(adminClient as any);

  const filesRepo = new FilesRepository();
  const imageLinksRepo = new ImageLinksRepository();
  const submissionsRepo = new SubmissionsRepository();
  const storageService = new SupabaseStorageService(adminClient);
  const coordinator = new SubmissionCoordinator({
    dbService: {
      files: filesRepo,
      imageLinks: imageLinksRepo,
      submissions: submissionsRepo,
      reviews: {} as any,
    } as any,
    storageService,
    compressImageFn: async (uri) => ({
      uri,
      originalUri: uri,
      preparedSizeBytes: 2048,
      sizeBytes: 2048,
      wasCompressed: true,
      reusedPrepared: false,
      mimeType: 'image/jpeg',
    }),
  });

  // =========================================================================
  // 1. Database Migrations, Schema & Constraint Verification
  // =========================================================================
  console.log('\n• Suite 1: Real Database Constraints & Migrations');

  await test('public.files accepts SUPABASE provider and relative provider_file_id', async () => {
    const testPath = `submissions/999/workers/test_${Date.now()}.jpg`;
    const record = await filesRepo.createFileRecord({
      storage_provider: 'SUPABASE',
      provider_file_id: testPath,
      file_name: 'test.jpg',
      size_bytes: 2048,
    });
    assert(record.id > 0);
    assert.strictEqual(record.storage_provider, 'SUPABASE');
    assert.strictEqual(record.provider_file_id, testPath);

    // Cleanup
    await filesRepo.deleteFileRecord(record.id);
  });

  await test('Foreign key fk_ppe_images_file enforces ON DELETE RESTRICT', async () => {
    // 1. Create file record
    const file = await filesRepo.createFileRecord({
      storage_provider: 'SUPABASE',
      provider_file_id: `submissions/999/workers/fk_test_${Date.now()}.jpg`,
      file_name: 'fk_test.jpg',
    });

    // 2. Link file in ppe_images
    // Note: requires valid worker instance
    const { data: sub } = await adminClient
      .from('ppe_submissions')
      .insert({ vendor_profile_id: 1, site_name: 'FK Test Site' })
      .select('id')
      .single();
    
    if (sub) {
      const { data: worker } = await adminClient
        .from('ppe_worker_instances')
        .insert({ submission_id: sub.id, sequence_no: 1 })
        .select('id')
        .single();

      if (worker) {
        await imageLinksRepo.linkPPEWorkerImage(worker.id, file.id, 'FRONT');

        // 3. Attempt to delete file record while referenced -> Must throw CONFLICT / RESTRICT
        let threw = false;
        try {
          await filesRepo.deleteFileRecord(file.id);
        } catch {
          threw = true;
        }
        assert.strictEqual(threw, true, 'deleteFileRecord was restricted by database reference check/FK');

        // 4. Release link, then delete must succeed
        await imageLinksRepo.deletePPEWorkerImage(worker.id, 'FRONT');
        const deleted = await filesRepo.deleteFileRecord(file.id);
        assert.strictEqual(deleted, true);

        // Teardown
        await adminClient.from('ppe_submissions').delete().eq('id', sub.id);
      }
    }
  });

  // =========================================================================
  // 2. Storage Buckets & Policies Verification
  // =========================================================================
  console.log('\n• Suite 2: Real Supabase Storage Bucket & Object Operations');

  await test('Upload, get metadata, signed URL, and delete in evidence bucket', async () => {
    const testPath = `submissions/1/workers/1_front_${Date.now()}_test.jpg`;
    const dummyBuffer = Buffer.from('FAKE_JPEG_IMAGE_BINARY_DATA');

    // Upload
    const uploadRes = await storageService.uploadFile({
      bucket: 'evidence',
      storagePath: testPath,
      fileBody: dummyBuffer,
      mimeType: 'image/jpeg',
      sizeBytes: dummyBuffer.length,
    });
    assert.strictEqual(uploadRes.storagePath, testPath);

    // Verify presence
    const exists = await storageService.fileExists('evidence', testPath);
    assert.strictEqual(exists, true);

    // Create signed URL
    const signed = await storageService.createSignedUrl('evidence', testPath, 60);
    assert(signed.signedUrl.startsWith('http'));

    // Delete
    const deleted = await storageService.deleteFile('evidence', testPath);
    assert.strictEqual(deleted, true);

    // Confirm removal
    const existsAfter = await storageService.fileExists('evidence', testPath);
    assert.strictEqual(existsAfter, false);
  });

  // =========================================================================
  // 3. Coordinator Workflows on Real Local Engine
  // =========================================================================
  console.log('\n• Suite 3: End-to-End Coordinator Workflows on Real Local Engine');

  await test('Coordinator submitOtherEvidence end-to-end on local Supabase', async () => {
    // 1. Create a synthetic test submission in DB
    const { data: sub } = await adminClient
      .from('ppe_submissions')
      .insert({ vendor_profile_id: 1, site_name: 'Coordinator Test Site' })
      .select('id')
      .single();

    if (sub) {
      const dummyFile = 'file:///tmp/synthetic_hazard.jpg';
      const result = await coordinator.submitOtherEvidence({
        submissionId: sub.id,
        sequenceNo: 1,
        localUri: dummyFile,
      });

      assert.strictEqual(result.status, 'COMPLETE_SUCCESS');
      assert(result.data);
      assert.strictEqual(result.data.submissionId, sub.id);

      // Verify in PostgreSQL
      const fileRec = await filesRepo.getFileRecordById(result.data.fileId);
      assert(fileRec);
      assert.strictEqual(fileRec.storage_provider, 'SUPABASE');

      // Verify in Supabase Storage
      const inStorage = await storageService.fileExists('evidence', result.data.storagePath);
      assert.strictEqual(inStorage, true);

      // Teardown
      await storageService.deleteFile('evidence', result.data.storagePath);
      await imageLinksRepo.deleteOtherImage(result.data.otherImageId);
      await filesRepo.deleteFileRecord(result.data.fileId);
      await adminClient.from('ppe_submissions').delete().eq('id', sub.id);
    }
  });

  console.log('\n=============================================================');
  console.log(`Local Supabase Results: ${passed}/${passed + failed} passed (${failed} failed)`);
  console.log('=============================================================\n');

  return {
    executed: true,
    passed,
    failed,
  };
}

// Direct execution runner
if (require.main === module) {
  runRealSupabaseIntegrationTests().then((res) => {
    if (res.executed && res.failed > 0) process.exit(1);
  });
}
