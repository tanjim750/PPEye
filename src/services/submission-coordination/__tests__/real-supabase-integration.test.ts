import { ImageLinksRepository } from '../../database/repositories/image-links.repository';
import { SubmissionsRepository } from '../../database/repositories/submissions.repository';
import { setDbClientOverride } from '../../database/client';
import { SupabaseStorageService, setSupabaseStorageClientOverride } from '../../storage/supabase-storage.client';
import { SubmissionCoordinator } from '../submission-coordinator';

const LOCAL_SUPABASE_URL = process.env.LOCAL_SUPABASE_URL || 'http://127.0.0.1:54321';
