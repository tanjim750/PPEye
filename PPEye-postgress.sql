-- 6. Access Policies
DO $$
DECLARE
  t text;
  tables text[] := ARRAY[
    'users', 'files', 'vendor_profiles', 'vendor_members', 'ppe_submissions',
    'ppe_worker_instances', 'ppe_images', 'other_images', 'ppe_reviews',
    'unsafe_reasons', 'ppe_review_reasons', 'other_reviews', 'submission_reviews'
  ];
BEGIN
  FOREACH t IN ARRAY tables LOOP
    EXECUTE format('DROP POLICY IF EXISTS "Allow all for authenticated users" ON public.%I', t);
    EXECUTE format('CREATE POLICY "Allow all for authenticated users" ON public.%I FOR ALL TO authenticated USING (true) WITH CHECK (true)', t);
    
    EXECUTE format('DROP POLICY IF EXISTS "Allow read for anon users" ON public.%I', t);
    EXECUTE format('CREATE POLICY "Allow read for anon users" ON public.%I FOR SELECT TO anon USING (true)', t);

    EXECUTE format('DROP POLICY IF EXISTS "Allow write for anon users" ON public.%I', t);
    EXECUTE format('CREATE POLICY "Allow write for anon users" ON public.%I FOR ALL TO anon USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;

