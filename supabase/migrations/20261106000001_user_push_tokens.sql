-- 4. SECURITY DEFINER RPCs for atomic login registration & logout unlinking
-- Supports both Supabase JWT sessions and verifyUserCredential custom sessions,
-- and prevents shared-device cross-user notification leaks by deactivating the
-- device token on any previously logged-in user_id.
CREATE OR REPLACE FUNCTION public.register_user_push_token(
  p_user_id BIGINT,
  p_push_token TEXT,
  p_device_type TEXT DEFAULT 'android'
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller_uid BIGINT;
  v_clean_token TEXT := trim(coalesce(p_push_token, ''));
  v_clean_device TEXT := lower(coalesce(nullif(trim(p_device_type), ''), 'android'));
BEGIN
  IF p_user_id IS NULL OR p_user_id <= 0 THEN
    RETURN false;
  END IF;

  IF v_clean_token !~ '^(ExponentPushToken|ExpoPushToken)\[[^\]]+\]$' THEN
    RETURN false;
  END IF;

  v_caller_uid := public.current_app_user_id();
  IF auth.role() <> 'service_role' AND v_caller_uid IS NOT NULL AND v_caller_uid <> p_user_id THEN
    RETURN false;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.users WHERE id = p_user_id AND is_active = true) THEN
    RETURN false;
  END IF;

  -- Unlink this physical device token from any other user who previously used this phone
  UPDATE public.user_push_tokens
     SET is_active = false,
         updated_at = now()
   WHERE push_token = v_clean_token
     AND user_id <> p_user_id
     AND is_active = true;

  UPDATE public.users
     SET expo_push_token = NULL,
         updated_at = now()
   WHERE expo_push_token = v_clean_token
     AND id <> p_user_id;

  -- Upsert active device token for target user
  INSERT INTO public.user_push_tokens (user_id, push_token, device_type, is_active, updated_at)
  VALUES (p_user_id, v_clean_token, left(v_clean_device, 32), true, now())
  ON CONFLICT (user_id, push_token)
  DO UPDATE SET
    device_type = EXCLUDED.device_type,
    is_active = true,
    updated_at = now();

  -- Mirror latest active token onto public.users for legacy lookups
  UPDATE public.users
     SET expo_push_token = v_clean_token,
         updated_at = now()
   WHERE id = p_user_id;

  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.unregister_user_push_token(
  p_user_id BIGINT,
  p_push_token TEXT DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller_uid BIGINT;
  v_clean_token TEXT := nullif(trim(coalesce(p_push_token, '')), '');
BEGIN
  IF p_user_id IS NULL AND v_clean_token IS NULL THEN
    RETURN false;
  END IF;

  v_caller_uid := public.current_app_user_id();
  IF auth.role() <> 'service_role'
     AND v_caller_uid IS NOT NULL
     AND p_user_id IS NOT NULL
     AND v_caller_uid <> p_user_id THEN
    RETURN false;
  END IF;

  IF v_clean_token IS NOT NULL THEN
    UPDATE public.user_push_tokens
       SET is_active = false,
           updated_at = now()
     WHERE push_token = v_clean_token
       AND (p_user_id IS NULL OR user_id = p_user_id);

    UPDATE public.users
       SET expo_push_token = NULL,
           updated_at = now()
     WHERE expo_push_token = v_clean_token
       AND (p_user_id IS NULL OR id = p_user_id);
  ELSIF p_user_id IS NOT NULL THEN
    UPDATE public.user_push_tokens
       SET is_active = false,
           updated_at = now()
     WHERE user_id = p_user_id
       AND is_active = true;

    UPDATE public.users
       SET expo_push_token = NULL,
           updated_at = now()
     WHERE id = p_user_id;
  END IF;

  RETURN true;
END;
$$;

GRANT EXECUTE ON FUNCTION public.register_user_push_token(BIGINT, TEXT, TEXT)
  TO anon, authenticated, service_role;

GRANT EXECUTE ON FUNCTION public.unregister_user_push_token(BIGINT, TEXT)
  TO anon, authenticated, service_role;
